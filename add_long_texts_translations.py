# Функция для обновления language.js
def update_language_js():
    """Добавляет новые переводы в language.js"""
    
    with open('language.js', 'r', encoding='utf-8') as f:
        content = f.read()
    
    # Находим секции для каждого языка
    for lang in ['ru', 'kz', 'en']:
        # Создаём новые строки переводов
        new_translations = ""
        for key, translations in ADDITIONAL_TRANSLATIONS.items():
            # Экранируем одинарные кавычки в тексте
            text = translations[lang].replace("'", "\\'")
            new_translations += f"        {key}: '{text}',\n"
        
        # Находим место для вставки (перед закрывающей скобкой секции языка)
        if lang == 'ru':
            # Вставляем перед "    },"
            pattern = "    },\n    \n    kz: {"
            replacement = new_translations + "    },\n    \n    kz: {"
        elif lang == 'kz':
            pattern = "    },\n    \n    en: {"
            replacement = new_translations + "    },\n    \n    en: {"
        else:  # en
            pattern = "    }\n};"
            replacement = new_translations + "    }\n};"
        
        content = content.replace(pattern, replacement)
    
    # Сохраняем
    with open('language.js', 'w', encoding='utf-8') as f:
        f.write(content)
    
    print(f"✅ language.js обновлён! Добавлено {len(ADDITIONAL_TRANSLATIONS)} новых ключей")

if __name__ == "__main__":
    update_language_js()
